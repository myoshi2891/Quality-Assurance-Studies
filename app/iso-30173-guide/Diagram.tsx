/** Render a named diagram and show its text alternative outside the image if rendering fails. */
export default function Diagram({ id }: { id: string }) {
  const [failed, setFailed] = useState(false);
  return (
    <>
      <div className="mermaid-diagram" id={id} tabIndex={0} role="img" aria-label={LABELS[id]}>
        <Mermaid chart={DIAGRAMS[id]!} onRenderError={() => setFailed(true)} />
      </div>
      {failed && (
        <>
          <p role="alert">図表の描画に失敗しました。以下の説明文と本文を参照してください。</p>
          <p>{LABELS[id]}</p>
        </>
      )}
    </>
  );
}
