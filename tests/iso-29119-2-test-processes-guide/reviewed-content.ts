/** Apply reviewed text corrections to archived source HTML. */
export function applyReviewedContent(html: string): string {
    return ARCHIVED_CONTENT_REPLACEMENTS.reduce(
        (acc, [from, to]) => acc.replaceAll(from, to),
        html,
    );
}
